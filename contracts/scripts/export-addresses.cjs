const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "../..");
const deploymentFile = path.join(root, "ignition/deployments/chain-11155111/deployed_addresses.json");
const outputFile = path.join(root, "app/lib/contracts.generated.ts");

if (!fs.existsSync(deploymentFile)) {
  throw new Error(`Sepolia deployment not found at ${deploymentFile}`);
}

const addresses = JSON.parse(fs.readFileSync(deploymentFile, "utf8"));
const required = {
  escrowImplementation: "FreelanceShield#Escrow",
  disputeResolver: "FreelanceShield#DisputeResolver",
  reputationRegistry: "FreelanceShield#ReputationRegistry",
  escrowFactory: "FreelanceShield#EscrowFactory",
};

for (const key of Object.values(required)) {
  if (!addresses[key]) throw new Error(`Missing Ignition address: ${key}`);
}

const contents = `// Generated by contracts/scripts/export-addresses.cjs after a Sepolia deployment.\nimport type { Address } from "viem";\n\nexport type FreelanceShieldContractConfig = {\n  chainId: 11155111;\n  network: "sepolia";\n  escrowImplementation: Address | null;\n  disputeResolver: Address | null;\n  reputationRegistry: Address | null;\n  escrowFactory: Address | null;\n};\n\nexport const freelanceShieldContracts: FreelanceShieldContractConfig = ${JSON.stringify({
  chainId: 11155111,
  network: "sepolia",
  escrowImplementation: addresses[required.escrowImplementation],
  disputeResolver: addresses[required.disputeResolver],
  reputationRegistry: addresses[required.reputationRegistry],
  escrowFactory: addresses[required.escrowFactory],
}, null, 2)};\n`;

fs.mkdirSync(path.dirname(outputFile), { recursive: true });
fs.writeFileSync(outputFile, contents);
console.log(`Wrote ${path.relative(root, outputFile)}`);
